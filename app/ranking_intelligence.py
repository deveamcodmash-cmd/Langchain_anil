"""Evidence-only LangGraph Rankings Agent.

The model may interpret wording, but cannot construct leaderboard participants.
Only the signed Joomla gateway can produce verified public ranking rows.
"""
import re
from .schemas import ChatRequest, ChatResponse

RANKING_INTENT=re.compile(r'\b(?:top\s*\d+|top\s+(?:donors?|corporat|campaign|charit|volunteers?|service)|highest|most\s+(?:donated|funded|raised|volunteered|followed)|leaderboards?|ranking|who\s+(?:donated|raised|volunteered)|where\s+do\s+i\s+rank|leading\s+(?:providers?|companies)|best\s+(?:service\s+)?providers?|followers?|most\s+popular\s+profiles?|donat(?:e|ed|ing)\s+(?:the\s+)?most|which\s+(?:corporat\w+|compan\w+)\s+are\s+donat)\b',re.I)
RANKING_FOLLOWUP=re.compile(r'^\s*(?:show\s+)?(?:last\s+month|this\s+month|this\s+year|all\s+time|top\s+(?:5|10|20)|show\s+more|only\s+corporate|only\s+individuals?)\s*[.!?]*$',re.I)


def ranking_intent(question: str, context = None) -> bool:
    return bool(RANKING_INTENT.search(question) or (context and RANKING_FOLLOWUP.fullmatch(question)))


def answer_ranking(request: ChatRequest) -> ChatResponse | None:
    # Account-specific giving history belongs to the authenticated account
    # query tool, not a public Top Donors leaderboard.
    if re.search(r'\b(?:where|which|how)\b.{0,60}\b(?:i|my)\b.{0,35}\bdonat',request.message,re.I) or re.search(r'\b(?:i|my)\b.{0,40}\bdonat\w*\b.{0,25}\bmost\b',request.message,re.I):
        return None
    evidence=request.ranking_data
    context=request.ranking_context
    # Even if a published global snapshot was accidentally provided, never
    # present it as a location/cause-filtered ranking. This preserves the
    # existing Joomla privacy/unsupported-filter guard during mixed upgrades.
    if context is not None and context.unsupported_filter:
        return ChatResponse(
            reply='A verified leaderboard with those location or cause filters is not published yet. I can help you explore the available public ranking categories.',
            mode='ranking_pending',agents_run=['Ranking Agent','Evidence Guard'])
    # Retain the legacy explicitly labelled partial-catalogue single-campaign
    # comparison when no new ranking evidence is supplied. Never claim Top N.
    if evidence is None and not re.search(r'\btop\s*\d+\b|\bleaderboards?\b|\branking\b',request.message,re.I) and re.search(r'\bcampaign\b',request.message,re.I):
        return None
    if not ranking_intent(request.message, context):
        return None
    if evidence is None or evidence.status!='published' or not evidence.verified:
        category=(evidence.type.replace('_',' ') if evidence else (context.type if context else 'requested'))
        if evidence is not None and evidence.message:
            reason=evidence.message
        else:
            reason=(f'The public {category} leaderboard is not published. '
                    'Verified source reconciliation and public visibility checks are required before any names, positions or amounts are shown.')
        # Never pad unavailable donor rankings with unrelated services, another
        # fake top-N list, or an unapproved publication timeline.
        return ChatResponse(reply=reason, mode='ranking_pending', agents_run=['Ranking Agent','Evidence Guard'])
    rows=evidence.rows[:5]
    if not rows:
        if evidence.summary is not None and evidence.summary.donations:
            summary=evidence.summary
            label=evidence.type.replace('_',' ').title()
            return ChatResponse(reply=(
                f'The recorded {label} leaderboard has no names available for public display under the existing profile settings. '
                f'However, the platform has {summary.donations:,} recorded paid donation entries in {summary.currency}, '
                f'totalling {summary.currency} {summary.amount:,.0f}. '
                f'{summary.contributors:,} distinct account(s) are linked to non-anonymous records in that currency. '
                'These are platform-wide recorded figures, not a Top 10 of named donors, and refunds are not reconciled.'),
                mode='ranking_summary',agents_run=['Ranking Agent','Recorded Giving Summary'])
        return ChatResponse(reply='No public profiles currently disclose donation rankings for this period. Your platform may still have recorded donations; hidden giving statistics are not published as named rankings.',
            mode='ranking_empty',agents_run=['Ranking Agent','Evidence Guard'])
    # No rank/person/score is ever generated by the model. Only provided rows.
    label='Provider Quality' if evidence.type=='providers' else evidence.type.replace('_',' ').title()
    basis=(evidence.message or '').strip()
    scope='administrator-only' if evidence.scope=='administrator' else 'public'
    anon = any(r.score is None for r in rows)
    phrasing = ('These are ordered anonymous positions; donor identities and individual amounts are not disclosed. ' if anon else '')
    return ChatResponse(reply=(f'Here are {len(rows)} {scope} {label} ranking entries from the existing recorded source. {evidence.total} currently eligible {scope} entries. {phrasing}{basis}')[:950],
        mode='ranking_public',agents_run=['Ranking Agent','Public Rankings API'])
